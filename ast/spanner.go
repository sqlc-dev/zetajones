// AlterColumnIdentityAction is the Spanner alter action "ALTER COLUMN c ALTER
// IDENTITY {SET SKIP RANGE min, max | SET NO SKIP RANGE | RESTART COUNTER WITH
// n}". Exactly one of SkipRange, NoSkipRange and RestartCounterWith is set.
type AlterColumnIdentityAction struct {
	Span
	Column             *Identifier                       `json:"column"`
	SkipRange          *IdentityColumnSkipRange          `json:"skip_range,omitempty"`
	NoSkipRange        bool                              `json:"no_skip_range,omitempty"`
	RestartCounterWith *IdentityColumnRestartCounterWith `json:"restart_counter_with,omitempty"`
}

func (n *AlterColumnIdentityAction) Children() []Node {
	return children(n.Column, n.SkipRange, n.RestartCounterWith)
}

