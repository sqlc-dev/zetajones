// GrantToRoleStatement is a Spanner fine-grained access control "GRANT
// privileges ON [object_type] objects TO ROLE roles" statement, or REVOKE
// ... FROM ROLE when IsRevoke is set. AllInSchema marks "ON ALL {TABLES |
// VIEWS | SEQUENCES ...} IN SCHEMA schema", where ObjectTypes holds the plural
// kind and Objects the schema names.
type GrantToRoleStatement struct {
	Span
	IsRevoke    bool                `json:"is_revoke,omitempty"`
	Privileges  *Privileges         `json:"privileges"`
	ObjectTypes []*Identifier       `json:"object_types,omitempty"`
	AllInSchema bool                `json:"all_in_schema,omitempty"`
	Objects     *PathExpressionList `json:"objects"`
	Roles       *IdentifierList     `json:"roles"`
}

func (n *GrantToRoleStatement) statementNode() {}
func (n *GrantToRoleStatement) Children() []Node {
	out := children(n.Privileges)
	for _, id := range n.ObjectTypes {
		out = append(out, id)
	}
	return append(out, children(n.Objects, n.Roles)...)
}

// GrantRoleStatement is the Spanner "GRANT ROLE roles TO ROLE grantees"
// statement, or "REVOKE ROLE roles FROM ROLE grantees" when IsRevoke is set.
type GrantRoleStatement struct {
	Span
	IsRevoke bool            `json:"is_revoke,omitempty"`
	Roles    *IdentifierList `json:"roles"`
	Grantees *IdentifierList `json:"grantees"`
}

func (n *GrantRoleStatement) statementNode()   {}
func (n *GrantRoleStatement) Children() []Node { return children(n.Roles, n.Grantees) }
