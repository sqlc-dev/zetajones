// This file holds nodes for Cloud Spanner DDL that GoogleSQL's reference
// parser does not accept (zetajones's SPANNER_DDL feature). They have no
// counterpart in googlesql/parser/parse_tree.h; their debug strings follow the
// same conventions as the reference nodes (see internal/dump/spanner.go).

